// The wire test vectors in testdata/vectors.json are what other implementations test against (see
// SPEC.md). They're generated here from the real encoders, every one checked by decoding it back,
// and this test fails if the file no longer matches: a wire change must regenerate it with
//
//	go test -run TestVectors -update-vectors
var updateVectors = flag.Bool("update-vectors", false, "rewrite testdata/vectors.json")

const vectorsPath = "testdata/vectors.json"

func TestVectors(t *testing.T) {
	v := buildVectors(t)
	enc, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	enc = append(enc, '\n')
	if *updateVectors {
		if err := os.MkdirAll(filepath.Dir(vectorsPath), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(vectorsPath, enc, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(vectorsPath)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(enc, want) {
		t.Fatalf("%s is stale: the wire format changed. If that's intended, update SPEC.md and run\n\tgo test -run TestVectors -update-vectors", vectorsPath)
	}
}

type obj = map[string]any

func hx(b []byte) string { return hex.EncodeToString(b) }

// seq returns n bytes counting up from start, for readable fixed keys.
func seq(start byte, n int) []byte {
	b := make([]byte, n)
	for i := range b {
		b[i] = start + byte(i)
	}
	return b
}

