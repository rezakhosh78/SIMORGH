var (
	vecServerSeed = seq(0x00, 32)
	vecClientEph  = seq(0x20, 32)
	vecServerEph  = seq(0x40, 32)
)

const vecSID = 0x2a5c

func cipherObj(c *packetCipher) obj {
	return obj{"key": hx(c.key[:]), "iv": hx(c.iv[:]), "hp": hx(c.hp[:])}
}

// vecSession performs the fixed handshake: the server's key, both ephemerals and the sid.
func vecSession(t *testing.T) (priv ed25519.PrivateKey, ceph, seph *ecdh.PrivateKey, reply []byte, up, down *packetCipher) {
	t.Helper()
	priv = ed25519.NewKeyFromSeed(vecServerSeed)
	ceph, _ = ecdh.X25519().NewPrivateKey(vecClientEph)
	seph, _ = ecdh.X25519().NewPrivateKey(vecServerEph)
	reply, up, down, err := serverHelloWith(priv, seph, ceph.PublicKey(), vecSID)
	if err != nil {
		t.Fatal(err)
	}
	sid, cup, cdown, err := clientFinish(priv.Public().(ed25519.PublicKey), ceph, reply)
	if err != nil || sid != vecSID || *cup != *up || *cdown != *down {
		t.Fatalf("handshake: sid %x, %v", sid, err)
	}
	return priv, ceph, seph, reply, up, down
}

func handshakeVectors(t *testing.T) (obj, *packetCipher, *packetCipher) {
	priv, ceph, seph, reply, up, down := vecSession(t)
	ee, _ := ceph.ECDH(seph.PublicKey())
	tr := transcript(ceph.PublicKey().Bytes(), seph.PublicKey().Bytes(), vecSID)
	prk, _ := hkdf.Extract(sha256.New, ee, tr)
	hello := append([]byte{0, 0}, ceph.PublicKey().Bytes()...)
	return obj{
		"server_seed":              hx(vecServerSeed),
		"server_public_key":        hx(priv.Public().(ed25519.PublicKey)),
		"client_ephemeral_private": hx(vecClientEph),
		"client_ephemeral_public":  hx(ceph.PublicKey().Bytes()),
		"server_ephemeral_private": hx(vecServerEph),
		"server_ephemeral_public":  hx(seph.PublicKey().Bytes()),
		"sid":                      vecSID,
		"hello_payload":            hx(hello),
		"shared_secret":            hx(ee),
		"transcript":               hx(tr),
		"prk":                      hx(prk),
		"up":                       cipherObj(up),
		"down":                     cipherObj(down),
		"hello_reply":              hx(reply),
	}, up, down
}

func packetVectors(t *testing.T, up, down *packetCipher) []obj {
	var out []obj
	for _, c := range []struct {
		pn    uint64
		plain []byte
	}{
		{0, append([]byte{0x50}, appendStream(nil, 0, 0, []byte("\x0fexample.com:443"), false, false)...)},
		{1, []byte{0x5f, frPing, 0, 0, 0}},
		{0x12345, append([]byte{0x00}, appendAck(nil, rangeSet{{0, 9}})...)},
	} {
		p := up.sealUp(vecSID, c.pn, c.plain)
		pn, plain, err := up.openUp(p, func(tr uint16) uint64 { return decodePN(c.pn-min(c.pn, 1), c.pn > 0, tr) })
		if err != nil || pn != c.pn || !bytes.Equal(plain, c.plain) {
			t.Fatalf("up pn %d: %v", c.pn, err)
		}
		out = append(out, obj{"direction": "up", "sid": vecSID, "pn": c.pn, "largest_received": largestBefore(c.pn), "plaintext": hx(c.plain),
			"nonce": hx(up.nonce(c.pn)), "mask": hx(func() []byte { m := up.mask(p[4:]); return m[:] }()), "payload": hx(p)})
	}
	for _, c := range []struct {
		pn, upPN uint64
		plain    []byte
		pad      int
	}{
		{0, 0, append([]byte{0, 0}, appendStream(ctrl{typ: frOpened, id: 0}.appendTo(nil), 0, 0, []byte("HTTP/1.1 200 OK\r\n"), false, false)...), 0},
		{1, 1, []byte{50, 3, 0, 0, 0, 0}, 0},
		{0x10000, 0x12345, append([]byte{0xff, 0xff}, ctrl{typ: frClose, val: 0}.appendTo(nil)...), 2},
	} {
		c.plain = append(c.plain, make([]byte, c.pad)...) // frames are at least 4 bytes
		p := down.sealDown(c.pn, c.upPN, c.plain)
		pn, plain, err := down.openDown(p, c.upPN, func(tr uint16) uint64 { return decodePN(c.pn-min(c.pn, 1), c.pn > 0, tr) })
		if err != nil || pn != c.pn || !bytes.Equal(plain, c.plain) {
			t.Fatalf("down pn %d: %v", c.pn, err)
		}
		out = append(out, obj{"direction": "down", "pn": c.pn, "up_pn": c.upPN, "largest_received": largestBefore(c.pn), "plaintext": hx(c.plain),
			"nonce": hx(down.nonce(c.pn)), "mask": hx(func() []byte { m := down.mask(p[2:]); return m[:] }()), "payload": hx(p)})
	}
	return out
}

// largestBefore is the largest_received a packet vector decodes with: the packet before it, or
// none (null) for pn 0.
func largestBefore(pn uint64) any {
	if pn == 0 {
		return nil
	}
	return pn - 1
}

func badPacketVectors(t *testing.T, up, down *packetCipher) []obj {
	plain := []byte{0x50, frPing, 0, 0, 0}
	good := up.sealUp(vecSID, 3, plain)
	flip := func(b []byte, i int) []byte {
		c := append([]byte(nil), b...)
		c[i] ^= 0x01
		return c
	}
	dgood := down.sealDown(3, 7, []byte{0, 0, frPing, 0, 0, 0})
	cases := []struct {
		name, dir string
		upPN      uint64
		p         []byte
	}{
		{"tag altered", "up", 0, flip(good, len(good)-1)},
		{"ciphertext altered", "up", 0, flip(good, 5)},
		{"session id altered (it is associated data)", "up", 0, flip(good, 1)},
		{"too short to sample", "up", 0, good[:4+sampleLen-1]},
		{"answer replayed onto another query", "down", 8, dgood},
		{"down tag altered", "down", 7, flip(dgood, len(dgood)-1)},
	}
	var out []obj
	for _, c := range cases {
		dec := func(tr uint16) uint64 { return decodePN(2, true, tr) }
		var err error
		if c.dir == "up" {
			_, _, err = up.openUp(c.p, dec)
		} else {
			_, _, err = down.openDown(c.p, c.upPN, dec)
		}
		if err == nil {
			t.Fatalf("bad packet %q accepted", c.name)
		}
		o := obj{"name": c.name, "direction": c.dir, "largest_received": 2, "payload": hx(c.p)}
		if c.dir == "down" {
			o["up_pn"] = c.upPN
		}
		out = append(out, o)
	}
	return out
}

func dnsVectors(t *testing.T, z zone) []obj {
	priv := ed25519.NewKeyFromSeed(vecServerSeed)
	var out []obj
	query := func(name string, txn uint16, payload []byte, qtype uint16) []byte {
		msg := appendQuery(nil, txn, payload, z, qtype, 1232)
		q, err := parseQuery(msg, z)
		if err != nil || !bytes.Equal(q.payload, payload) || q.qtype != qtype || q.txn != txn {
			t.Fatalf("query %q: %v", name, err)
		}
		out = append(out, obj{"name": name, "kind": "query", "build": true, "txn": txn, "qtype": qtype, "edns_size": 1232,
			"payload": hx(payload), "message": hx(msg)})
		return msg
	}
	answer := func(name string, qmsg []byte, rcode byte, payload []byte) []byte {
		q, _ := parseQuery(qmsg, z)
		msg := appendAnswer(nil, q, rcode, payload)
		a, err := parseAnswer(msg)
		if err != nil || !bytes.Equal(a.txt, payload) || a.rcode != int(rcode) || a.hasTXT != (payload != nil) {
			t.Fatalf("answer %q: %v", name, err)
		}
		o := obj{"name": name, "kind": "answer", "subkind": "carrier", "build": true, "query": hx(qmsg), "rcode": rcode, "message": hx(msg)}
		if payload != nil {
			o["payload"] = hx(payload)
		} else {
			o["subkind"] = "empty"
		}
		out = append(out, o)
		return msg
	}

	hello := append([]byte{0, 0}, seq(0x80, 32)...)
	qTXT := query("hello, TXT", 0x1234, hello, typeTXT)
	query("data at the safe name length", 0xBEEF, seq(0, z.maxPayload(101)), typeTXT)
	query("data at the full name length", 0x0001, seq(0, z.maxPayload(253)), typeTXT)
	qAAAA := query("AAAA carrier", 0x4321, seq(0x10, 20), typeAAAA)

	// Resolvers may randomize the case of the name (DNS 0x20).
	mixed := append([]byte(nil), qTXT...)
	end, _ := skipName(mixed, hdrLen)
	for i := hdrLen; i < end; i += 2 {
		if c := mixed[i]; c >= 'a' && c <= 'z' {
			mixed[i] = c - 'a' + 'A'
		}
	}
	if q, _ := parseQuery(mixed, z); q == nil || !bytes.Equal(q.payload, hello) {
		t.Fatal("mixed case query")
	}
	out = append(out, obj{"name": "hello with randomized case", "kind": "query", "build": false, "txn": 0x1234, "qtype": typeTXT,
		"edns_size": 1232, "payload": hx(hello), "message": hx(mixed)})

	answer("TXT, one string", qTXT, rcodeOK, seq(0, 98))
	answer("TXT, several strings", qTXT, rcodeOK, seq(0, 600))
	answer("TXT, empty payload", qTXT, rcodeOK, []byte{})
	aaaa := answer("AAAA, numbered chunks", qAAAA, rcodeOK, seq(0x30, 40))
	answer("REFUSED, no records", qTXT, rcodeRefused, nil)

	// The AAAA records in reverse order still reassemble.
	q, _ := parseQuery(qAAAA, z)
	start := hdrLen + len(q.question)
	recs := (len(aaaa) - start - 11) / aaaaRRLen
	rev := append([]byte(nil), aaaa[:start]...)
	for i := recs - 1; i >= 0; i-- {
		rev = append(rev, aaaa[start+i*aaaaRRLen:start+(i+1)*aaaaRRLen]...)
	}
	rev = append(rev, aaaa[start+recs*aaaaRRLen:]...)
	if a, err := parseAnswer(rev); err != nil || !bytes.Equal(a.txt, seq(0x30, 40)) {
		t.Fatal("reordered AAAA", err)
	}
	out = append(out, obj{"name": "AAAA, records reordered by a resolver", "kind": "answer", "subkind": "carrier", "build": false, "query": hx(qAAAA),
		"rcode": 0, "payload": hx(seq(0x30, 40)), "message": hx(rev)})

	// Unknown session: NXDOMAIN carrying the server's signature over the lower-cased question.
	unk := appendQuery(nil, 0x7777, append([]byte{0x99, 0x99}, seq(0, 20)...), z, typeTXT, 1232)
	uq, _ := parseQuery(unk, z)
	sig := ed25519.Sign(priv, unknownSessionMsg(uq.question))
	umsg := appendAnswer(nil, uq, rcodeNXDomain, sig)
	if a, _ := parseAnswer(umsg); !ed25519.Verify(priv.Public().(ed25519.PublicKey), unknownSessionMsg(a.question), a.txt) {
		t.Fatal("unknown-session signature")
	}
	out = append(out, obj{"name": "unknown session, signed", "kind": "answer", "subkind": "unknown_session", "build": true, "query": hx(unk), "rcode": rcodeNXDomain,
		"payload": hx(sig), "signed_message": hx(unknownSessionMsg(uq.question)), "message": hx(umsg)})

	// In-zone queries that aren't tunnel traffic get NOERROR with the zone's SOA.
	for _, c := range []struct {
		name  string
		qname []byte
		qtype uint16
	}{
		{"SOA at the apex", nil, typeSOA},
		{"A query under the zone (QNAME minimisation)", []byte("\x03www"), 1},
	} {
		msg := []byte{0xab, 0xcd, 0x01, 0x00, 0, 1, 0, 0, 0, 0, 0, 0}
		msg = append(append(append(msg, c.qname...), z.wire...), 0)
		msg = append(msg, byte(c.qtype>>8), byte(c.qtype), 0, 1)
		q, err := parseQuery(msg, z)
		if err != nil {
			t.Fatal(err)
		}
		out = append(out, obj{"name": "no data: " + c.name, "kind": "answer", "subkind": "no_data", "build": true, "query": hx(msg), "rcode": 0,
			"message": hx(appendNoData(nil, q, z))})
	}

	for _, c := range []struct {
		name  string
		msg   []byte
		limit int
	}{
		{"TXT", qTXT, 512}, {"TXT", qTXT, 1232}, {"AAAA", qAAAA, 512}, {"AAAA", qAAAA, 1232},
	} {
		q, _ := parseQuery(c.msg, z)
		n := capacity(q, c.limit)
		if a := appendAnswer(nil, q, rcodeOK, make([]byte, n)); len(a) > c.limit {
			t.Fatalf("capacity %s/%d", c.name, c.limit)
		}
		out = append(out, obj{"name": "capacity, " + c.name, "kind": "capacity", "query": hx(c.msg), "limit": c.limit, "capacity": n})
	}
	return out
}

// exchangeVectors is a whole session in DNS messages: the handshake, a stream opened with a
// request, its response, and the client's acknowledgement.
func exchangeVectors(t *testing.T, z zone) []obj {
	priv, ceph, _, reply, up, down := vecSession(t)
	var out []obj
	step := func(desc string, q []byte, a []byte, extra obj) {
		o := obj{"description": desc, "query": hx(q), "answer": hx(a)}
		maps.Copy(o, extra)
		out = append(out, o)
	}
	ask := func(txn uint16, payload []byte) (*query, []byte) {
		msg := appendQuery(nil, txn, payload, z, typeTXT, 1232)
		q, err := parseQuery(msg, z)
		if err != nil || !bytes.Equal(q.payload, payload) {
			t.Fatal(err)
		}
		return q, msg
	}
	// 1. Hello.
	hq, hmsg := ask(0x0101, append([]byte{0, 0}, ceph.PublicKey().Bytes()...))
	hans := appendAnswer(nil, hq, rcodeOK, reply)
	a, _ := parseAnswer(hans)
	if _, _, _, err := clientFinish(priv.Public().(ed25519.PublicKey), ceph, a.txt); err != nil {
		t.Fatal(err)
	}
	step("hello and the server's signed reply", hmsg, hans, obj{"hello_payload": hx(hq.payload), "hello_reply": hx(reply)})

	dec := func(largest uint64, have bool) func(uint16) uint64 {
		return func(tr uint16) uint64 { return decodePN(largest, have, tr) }
	}
	// 2. Open stream 0 to example.com:443 and send a request; hold 500ms, answers up to 512 bytes.
	req := []byte("\x0fexample.com:443GET / HTTP/1.1\r\nHost: example.com\r\n\r\n")
	up0 := append([]byte{0x50}, appendStream(nil, 0, 0, req, false, false)...)
	q, qmsg := ask(0x0202, up.sealUp(vecSID, 0, up0))
	if pn, plain, err := up.openUp(q.payload, dec(0, false)); err != nil || pn != 0 || !bytes.Equal(plain, up0) {
		t.Fatal("exchange up 0", err)
	}
	resp := []byte("HTTP/1.1 204 No Content\r\n\r\n")
	down0 := append([]byte{0, 0}, appendStream(ctrl{typ: frOpened, id: 0}.appendTo(nil), 0, 0, resp, false, false)...)
	amsg := appendAnswer(nil, q, rcodeOK, down.sealDown(0, 0, down0))
	a, _ = parseAnswer(amsg)
	if pn, plain, err := down.openDown(a.txt, 0, dec(0, false)); err != nil || pn != 0 || !bytes.Equal(plain, down0) {
		t.Fatal("exchange down 0", err)
	}
	step("a stream opened with a request, answered with OPENED and the response", qmsg, amsg,
		obj{"up_pn": 0, "up_plaintext": hx(up0), "down_pn": 0, "down_plaintext": hx(down0)})

	// 3. The client acknowledges downstream packet 0 and finishes its side. Its FIN is a STREAM
	// frame, so the server answers at once (SPEC §7.2), with its own FIN.
	up1 := append([]byte{0x50}, appendStream(appendAck(nil, rangeSet{{0, 1}}), 0, uint64(len(req)), nil, true, false)...)
	q, qmsg = ask(0x0303, up.sealUp(vecSID, 1, up1))
	if pn, plain, err := up.openUp(q.payload, dec(0, true)); err != nil || pn != 1 || !bytes.Equal(plain, up1) {
		t.Fatal("exchange up 1", err)
	}
	down1 := append([]byte{0, 0}, appendStream(nil, 0, uint64(len(resp)), nil, true, false)...)
	amsg = appendAnswer(nil, q, rcodeOK, down.sealDown(1, 1, down1))
	a, _ = parseAnswer(amsg)
	if pn, plain, err := down.openDown(a.txt, 1, dec(0, true)); err != nil || pn != 1 || !bytes.Equal(plain, down1) {
		t.Fatal("exchange down 1", err)
	}
	step("the client acks and sends FIN; the server answers at once with its FIN", qmsg, amsg,
		obj{"up_pn": 1, "up_plaintext": hx(up1), "down_pn": 1, "down_plaintext": hx(down1)})
	return out
}
