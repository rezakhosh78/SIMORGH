// frameObj describes a parsed frame for the vectors.
func frameObj(f *frame) obj {
	switch {
	case f.typ == frPing:
		return obj{"type": "ping"}
	case f.typ == frAck:
		rs := [][2]uint64{}
		for _, r := range f.ranges {
			rs = append(rs, [2]uint64{r.lo, r.hi})
		}
		return obj{"type": "ack", "ranges": rs}
	case f.typ == frReset:
		return obj{"type": "reset_stream", "id": f.id, "code": f.val}
	case f.typ == frMaxStream:
		return obj{"type": "max_stream_data", "id": f.id, "max": f.val}
	case f.typ == frClose:
		return obj{"type": "close", "code": f.val}
	case f.typ == frLost:
		return obj{"type": "lost", "pns": f.lost}
	case f.typ == frOpened:
		return obj{"type": "opened", "id": f.id}
	default:
		return obj{"type": "stream", "id": f.id, "offset": f.off, "data": hx(f.data), "fin": f.fin,
			"explicit_length": f.typ&streamLen != 0}
	}
}

func parsedFrames(t *testing.T, b []byte) []obj {
	t.Helper()
	out := []obj{}
	if err := parseFrames(b, func(f *frame) error { out = append(out, frameObj(f)); return nil }); err != nil {
		t.Fatalf("frames %x: %v", b, err)
	}
	return out
}

func frameVectors(t *testing.T) []obj {
	cases := []struct {
		name string
		enc  []byte
		want []obj
	}{
		{"ping", []byte{frPing}, []obj{{"type": "ping"}}},
		{"padding runs to the end of the packet", []byte{frPing, frPadding, 0, 0, 0x55}, []obj{{"type": "ping"}}},
		{"ack, one range", appendAck(nil, rangeSet{{0, 1}}), []obj{{"type": "ack", "ranges": [][2]uint64{{0, 1}}}}},
		{"ack, three ranges", appendAck(nil, rangeSet{{1, 3}, {5, 6}, {9, 20}}),
			[]obj{{"type": "ack", "ranges": [][2]uint64{{1, 3}, {5, 6}, {9, 20}}}}},
		{"ack, large numbers", appendAck(nil, rangeSet{{70000, 70100}, {80000, 80001}}),
			[]obj{{"type": "ack", "ranges": [][2]uint64{{70000, 70100}, {80000, 80001}}}}},
		{"reset_stream", ctrl{typ: frReset, id: 4, val: 1}.appendTo(nil), []obj{{"type": "reset_stream", "id": 4, "code": 1}}},
		{"max_stream_data", ctrl{typ: frMaxStream, id: 3, val: 1 << 20}.appendTo(nil), []obj{{"type": "max_stream_data", "id": 3, "max": 1 << 20}}},
		{"close", ctrl{typ: frClose, val: 7}.appendTo(nil), []obj{{"type": "close", "code": 7}}},
		{"lost", appendLost(nil, []uint64{40, 7, 6, 0}), []obj{{"type": "lost", "pns": []uint64{40, 7, 6, 0}}}},
		{"opened", ctrl{typ: frOpened, id: 9}.appendTo(nil), []obj{{"type": "opened", "id": 9}}},
		{"stream, offset 0, explicit length", appendStream(nil, 0, 0, []byte("hello"), false, false),
			[]obj{{"type": "stream", "id": 0, "offset": 0, "data": hx([]byte("hello")), "fin": false, "explicit_length": true}}},
		{"stream, offset and FIN", appendStream(nil, 2, 100, []byte("tail"), true, false),
			[]obj{{"type": "stream", "id": 2, "offset": 100, "data": hx([]byte("tail")), "fin": true, "explicit_length": true}}},
		{"stream, bare FIN", appendStream(nil, 1, 4096, nil, true, false),
			[]obj{{"type": "stream", "id": 1, "offset": 4096, "data": "", "fin": true, "explicit_length": true}}},
		{"stream without length runs to the end of the packet", appendStream(nil, 7, 0, []byte("rest"), true, true),
			[]obj{{"type": "stream", "id": 7, "offset": 0, "data": hx([]byte("rest")), "fin": true, "explicit_length": false}}},
	}
	var out []obj
	for _, c := range cases {
		got := parsedFrames(t, c.enc)
		if !jsonEqual(got, c.want) {
			t.Fatalf("frame %q: parsed %v, want %v", c.name, got, c.want)
		}
		out = append(out, obj{"name": c.name, "encoded": hx(c.enc), "frames": c.want})
	}
	// Several frames in one packet, as the session builds them.
	var b []byte
	b = ctrl{typ: frMaxStream, id: 0, val: 256 << 10}.appendTo(b)
	b = appendLost(b, []uint64{12})
	b = appendAck(b, rangeSet{{0, 4}})
	b = appendStream(b, 0, 0, []byte("\x0fexample.com:443"), false, false)
	out = append(out, obj{"name": "a packet's worth", "encoded": hx(b), "frames": parsedFrames(t, b)})
	return out
}

func jsonEqual(a, b any) bool {
	ja, _ := json.Marshal(a)
	jb, _ := json.Marshal(b)
	var x, y any
	json.Unmarshal(ja, &x)
	json.Unmarshal(jb, &y)
	return reflect.DeepEqual(x, y)
}

