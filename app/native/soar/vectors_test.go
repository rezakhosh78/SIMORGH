func varintVectors(t *testing.T) []obj {
	var out []obj
	for _, v := range []uint64{0, 37, 63, 64, 15293, 16383, 16384, 494878333, 1<<30 - 1, 1 << 30, 151288809941952652, maxVarint} {
		enc := appendVarint(nil, v)
		r := reader{b: enc}
		if got := r.varint(); got != v || r.err != nil || len(r.b) != 0 {
			t.Fatalf("varint %d round trip", v)
		}
		out = append(out, obj{"value": v, "encoded": hx(enc)})
	}
	return out
}

func base32Vectors(t *testing.T) []obj {
	var out []obj
	for _, d := range [][]byte{{}, {0}, {0xFF}, []byte("f"), []byte("fo"), []byte("foo"), []byte("foob"), []byte("fooba"), []byte("foobar"), seq(0xF0, 16)} {
		enc := b32Append(nil, d)
		got, err := b32Decode(nil, enc)
		if err != nil || !bytes.Equal(got, d) {
			t.Fatalf("base32 %x round trip", d)
		}
		if got, _ := b32Decode(nil, bytes.ToUpper(enc)); !bytes.Equal(got, d) {
			t.Fatalf("base32 %x upper case", d)
		}
		out = append(out, obj{"data": hx(d), "encoded": string(enc)})
	}
	return out
}

func nameCapacityVectors(t *testing.T) []obj {
	var out []obj
	for _, zs := range []string{"t.example.com", "x.y"} {
		z, _ := parseZone(zs)
		for _, n := range []int{101, 150, 253} {
			m := z.maxPayload(n)
			msg := appendQuery(nil, 0, make([]byte, m), z, typeTXT, 1232)
			end, _ := skipName(msg, hdrLen)
			if pres := end - hdrLen - 2; pres > n {
				t.Fatalf("%s/%d: name %d chars", zs, n, pres)
			}
			out = append(out, obj{"zone": zs, "max_name_length": n, "max_payload": m})
		}
	}
	return out
}

